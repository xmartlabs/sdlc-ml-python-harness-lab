#!/usr/bin/env python3
"""Start a benchmark run: register, create workspace, inject prompt, launch opencode.

Usage (prefer make):
    make bench-start RUN=tetris-v1-A-002 [KEY=sk-xxx]
    uv run python scripts/bench_start.py --run tetris-v1-A-002 [--key sk-xxx] [--no-launch]
"""
from __future__ import annotations

import argparse
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path

# Shared helpers live in create_run — import without side-effects
sys.path.insert(0, str(Path(__file__).parent))
from create_run import (
    DATA_DIR,
    REPO_ROOT,
    RUNS_FILES,
    _load_env,
    create_litellm_key,
    find_run,
    scaffold_report,
    set_status_running,
)

WORKSPACE_ROOT = REPO_ROOT / "workspace"
BENCH_CONTEXT = REPO_ROOT / "BENCH_CONTEXT.md"
BENCH_CONTEXT_PLACEHOLDER = "<!-- No active benchmark run. Generated by make bench-start. -->\n"

PROMPT_SOURCES: dict[str, Path] = {
    "tetris-v1": REPO_ROOT / "benchmarks" / "tetris" / "prompt_incremental.md",
}


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    p = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    p.add_argument("--run", required=True, help="run_id, e.g. tetris-v1-A-002")
    p.add_argument("--benchmark", default="tetris-v1", help="benchmark_id (default: tetris-v1)")
    p.add_argument("--key", help="LiteLLM virtual key (sk-...). If omitted, auto-creation is attempted.")
    p.add_argument(
        "--no-launch", action="store_true",
        help="Set up everything but do not exec opencode (useful for testing)"
    )
    return p.parse_args(argv)


def patch_env_token(env_path: Path, key: str) -> bool:
    """Replace GATEWAY_TOKEN line in .env. Returns True if patched."""
    if not env_path.exists():
        return False
    text = env_path.read_text()
    new_text = re.sub(r"^GATEWAY_TOKEN=.*$", f"GATEWAY_TOKEN={key}", text, flags=re.MULTILINE)
    if new_text == text:
        return False
    env_path.write_text(new_text)
    return True


def restore_env_token(env_path: Path) -> None:
    patch_env_token(env_path, "sk-local-change-me")


def generate_prompt(run_id: str, benchmark: str, out_dir: Path) -> Path:
    source = PROMPT_SOURCES.get(benchmark)
    if source is None or not source.exists():
        sys.exit(f"No prompt source for benchmark '{benchmark}' at {source}")
    header = (
        f"# Benchmark run: {run_id}\n\n"
        f"> All files must be created in `workspace/{run_id}/`\n"
        f"> Entry point: `workspace/{run_id}/main.py`\n\n"
        f"---\n\n"
    )
    prompt_path = out_dir / "prompt.md"
    prompt_path.write_text(header + source.read_text())
    return prompt_path


def write_bench_context(run_id: str) -> None:
    BENCH_CONTEXT.write_text(
        f"# Benchmark run activo: {run_id}\n\n"
        f"**IMPORTANT — non-negotiable constraints for this session:**\n\n"
        f"- All files MUST be created inside `workspace/{run_id}/`\n"
        f"- The entry point is `workspace/{run_id}/main.py`\n"
        f"- Do NOT create or modify any files outside `workspace/{run_id}/`\n"
        f"- To validate each increment: `python workspace/{run_id}/main.py`\n"
        f"- Do NOT modify any other files in the repository\n"
    )


def copy_to_clipboard(text: str) -> bool:
    try:
        subprocess.run(["pbcopy"], input=text.encode(), check=True, capture_output=True)
        return True
    except (FileNotFoundError, subprocess.CalledProcessError):
        return False


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv)
    _load_env()

    runs_path = RUNS_FILES.get(args.benchmark)
    if runs_path is None:
        sys.exit(f"Unknown benchmark '{args.benchmark}'. Known: {list(RUNS_FILES)}")

    run = find_run(runs_path, args.run)
    if run.get("status") == "completed":
        sys.exit(f"Run {args.run} is already completed. Use a new run_id.")

    # 1. Register run (report + status)
    out_dir = DATA_DIR / args.run
    out_dir.mkdir(parents=True, exist_ok=True)
    if not (out_dir / "report.md").exists():
        scaffold_report(run, out_dir)
    set_status_running(runs_path, args.run)

    # 2. Create workspace
    workspace = WORKSPACE_ROOT / args.run
    workspace.mkdir(parents=True, exist_ok=True)

    # 3. Generate prompt with workspace path injected
    prompt_path = generate_prompt(args.run, args.benchmark, out_dir)

    # 4. Write BENCH_CONTEXT.md (read by opencode via opencode.json instructions)
    write_bench_context(args.run)

    # 5. Resolve virtual key
    run_key: str | None = args.key
    key_error: str | None = None

    if run_key is None:
        gateway_base = os.environ.get("GATEWAY_BASE_URL", "")
        master_key = os.environ.get("LITELLM_MASTER_KEY", "")
        if not gateway_base:
            key_error = "GATEWAY_BASE_URL not set in .env"
        elif not master_key:
            key_error = "LITELLM_MASTER_KEY not set in .env"
        else:
            try:
                run_key = create_litellm_key(gateway_base, master_key, run)
            except RuntimeError as e:
                key_error = str(e)

    # 6. Patch .env + update current process env (so os.execv inherits it)
    env_path = REPO_ROOT / ".env"
    patched = False
    if run_key:
        patched = patch_env_token(env_path, run_key)
        os.environ["GATEWAY_TOKEN"] = run_key  # inherited by opencode via execv

    # 7. Copy prompt to clipboard
    prompt_text = prompt_path.read_text()
    clipped = copy_to_clipboard(prompt_text)

    # 8. Print summary
    session_id = run.get("langfuse_session_id", "")
    models = run.get("gateway_models", [])
    print()
    print("=" * 66)
    print(f"  bench-start: {args.run}")
    print("=" * 66)
    print(f"  Workspace:   workspace/{args.run}/")
    print(f"  Prompt:      data/runs/{args.run}/prompt.md")
    if session_id:
        print(f"  Session ID:  {session_id}")
    if models:
        print(f"  Models:      {', '.join(models)}")
    print()

    if run_key:
        print(f"  Key:         {run_key}")
        if patched:
            print("  .env GATEWAY_TOKEN patched ✓")
    else:
        gw = os.environ.get("GATEWAY_BASE_URL", "http://localhost:4000")
        base = gw.rstrip("/").removesuffix("/v1")
        print(f"  Key creation skipped: {key_error}")
        print(f"  Create key manually: {base}/ui -> Keys -> New Key")
        print(f"    alias: {args.run}   metadata.session_id: {session_id or args.run}")
        print("  Then set GATEWAY_TOKEN=<key> in .env before running opencode.")

    print()
    if clipped:
        print("  Prompt copied to clipboard ✓ — paste with Cmd+V in OpenCode")
    else:
        print(f"  Paste prompt from:  cat data/runs/{args.run}/prompt.md")

    print()
    print("  When done, in another terminal:")
    print(f"    make bench-close RUN={args.run} SCORE=<0-10> INTERVENTIONS=<N>")
    print("=" * 66)

    if args.no_launch:
        print()
        print("  (--no-launch set: opencode not started)")
        return 0

    # 9. Exec opencode — replaces this process, inherits patched os.environ
    opencode_bin = shutil.which("opencode")
    if not opencode_bin:
        sys.exit("❌ opencode not found. Install: brew install anomalyco/tap/opencode")
    os.execv(opencode_bin, [opencode_bin])
    return 0  # unreachable


if __name__ == "__main__":
    sys.exit(main())
