"""Git operations behind ad hoc tasks: the clean patch, and applying it (ADR-0095).

Standard library only, on purpose. The same file runs in two places: inside the
lab's own processes (to build and read a patch) and as ``python adhoc_git.py``
inside the short-lived container that mounts the operator's folder read-write.
That container has the worker image's Python but none of the lab's settings or
database, so nothing here may import from ``harness_lab_app``.

Three rules make "apply" safe on somebody's working copy:

* **all or nothing** — ``git apply`` refuses the whole patch when one hunk does
  not fit, so a failed apply leaves the folder exactly as it was;
* **files only** — no ``--index``, no commit, no branch, no stash: the change
  appears as uncommitted edits and the operator commits it themselves;
* **check first** — an operation in progress, a held index lock, or an
  uncommitted edit in a file the patch touches refuses before anything is
  written.
"""

from __future__ import annotations

import json
import os
import re
import subprocess  # nosec B404 - list form, fixed env, operator's own repository
import sys
import tempfile
from dataclasses import asdict, dataclass, field
from pathlib import Path

_GIT_ENV = {
    "GIT_TERMINAL_PROMPT": "0",
    "GIT_SSH_COMMAND": "ssh -oBatchMode=yes",
    "GIT_ASKPASS": "",
    "PATH": "/usr/bin:/bin:/usr/local/bin",
    # A folder mounted from the host belongs to another uid; without this git
    # refuses to read it ("dubious ownership") before doing anything.
    "GIT_CONFIG_COUNT": "1",
    "GIT_CONFIG_KEY_0": "safe.directory",
    "GIT_CONFIG_VALUE_0": "*",
}

# Paths a change should not carry without a second look. Not refused: flagged,
# because a lockfile regenerated by an install is usually noise and sometimes
# exactly the fix.
_LOCKFILES = {
    "uv.lock",
    "poetry.lock",
    "Pipfile.lock",
    "package-lock.json",
    "yarn.lock",
    "pnpm-lock.yaml",
    "Cargo.lock",
    "go.sum",
    "Gemfile.lock",
    "composer.lock",
}
_CI_PREFIXES = (".github/workflows/", ".gitlab-ci", ".circleci/", "Jenkinsfile")
_SECRET_LIKE = re.compile(
    r"(^|/)(\.env(\..*)?|.*\.pem|.*\.key|id_rsa.*|credentials.*|.*secret.*)$",
    re.IGNORECASE,
)
_LARGE_LINES = 800

# What an agent leaves behind by installing or running things. Kept out of the
# change even when the repository forgot to ignore them.
_NOISE_DIRS = (
    "node_modules/",
    ".venv/",
    "venv/",
    "__pycache__/",
    ".pytest_cache/",
    ".mypy_cache/",
    ".ruff_cache/",
    ".tox/",
)


class AdhocGitError(RuntimeError):
    """A git step failed in a way the operator has to hear about."""


def git(args: list[str], cwd: Path, timeout: int = 120) -> tuple[int, str, str]:
    """Run git with a fixed environment; never raises on a non-zero exit."""
    try:
        result = subprocess.run(  # nosec B603 - list form, fixed env
            ["git", *args],
            cwd=str(cwd),
            capture_output=True,
            text=True,
            timeout=timeout,
            env=_GIT_ENV,
            check=False,
        )
    except FileNotFoundError:  # pragma: no cover - git is in every image
        return 127, "", "git is not available"
    except subprocess.TimeoutExpired:
        return 124, "", f"git {args[0]} timed out after {timeout}s"
    return result.returncode, result.stdout, result.stderr


def _git_ok(args: list[str], cwd: Path, timeout: int = 120) -> str:
    code, out, err = git(args, cwd, timeout)
    if code != 0:
        raise AdhocGitError(f"git {' '.join(args[:2])} failed: {(err or out).strip()}")
    return out


# --------------------------------------------------------------------------
# The patch
# --------------------------------------------------------------------------


@dataclass
class PatchFile:
    path: str
    added: int = 0
    removed: int = 0
    status: str = "modified"  # added | modified | deleted | renamed
    binary: bool = False
    flags: list[str] = field(default_factory=list)


_PROVISIONED_SUBJECT = "^target: provisioned "


def provisioned_commit(workspace: Path, base_commit: str) -> str:
    """The lab's provisioning commit on top of ``base_commit``, or "".

    The runner commits the operator's tree plus whatever setup produced and
    whatever harness it projected, before the agent starts (ADR-0030). Only
    commits after ``base_commit`` are searched, so a message in the operator's
    own history that happens to say "provisioned" is never picked.
    """
    code, out, _ = git(
        [
            "log",
            "--format=%H",
            "-n",
            "1",
            f"--grep={_PROVISIONED_SUBJECT}",
            f"{base_commit}..HEAD",
        ],
        workspace,
    )
    return out.strip() if code == 0 else ""


def build_change_patch(workspace: Path, base_commit: str) -> str:
    """The agent's change, ready for ``git apply`` on the operator's commit.

    Diffed against the lab's provisioning commit, not against ``base_commit``:
    the provisioning commit already holds setup output and any projected
    harness, so neither leaks into the operator's repository as if the agent
    had written it. The provisioning tree equals ``base_commit`` everywhere the
    agent could reasonably touch, so the hunks apply on the operator's commit.
    A diff against a commit (not ``HEAD``) also survives an agent that committed
    its own work inside the copy.

    ``--binary`` because an image or a binary fixture would otherwise appear as
    "Binary files differ", which ``git apply`` cannot apply. Intent-to-add makes
    new files visible to the diff without staging their content; ``.gitignore``
    still applies to them, and the noise directories are excluded even when the
    repository forgot to ignore them.
    """
    if not (workspace / ".git").exists():
        raise AdhocGitError(f"{workspace} is not a git repository.")
    diff_from = provisioned_commit(workspace, base_commit) or base_commit
    _git_ok(["add", "--intent-to-add", "--all"], workspace)
    excludes = [f":(exclude,glob)**/{name}**" for name in _NOISE_DIRS]
    code, out, err = git(
        [
            "diff",
            "--binary",
            "--no-color",
            "--no-ext-diff",
            diff_from,
            "--",
            ".",
            *excludes,
        ],
        workspace,
        timeout=300,
    )
    if code != 0:
        raise AdhocGitError(f"git diff failed: {err.strip()}")
    return out


_DIFF_HEADER = re.compile(r"^diff --git a/(.+?) b/(.+)$")


def summarize_patch(patch: str) -> list[PatchFile]:
    """Per-file counts and review flags, read from the patch text alone."""
    files: list[PatchFile] = []
    current: PatchFile | None = None
    for line in patch.splitlines():
        header = _DIFF_HEADER.match(line)
        if header:
            current = PatchFile(path=header.group(2))
            files.append(current)
            continue
        if current is None:
            continue
        if line.startswith("new file mode"):
            current.status = "added"
        elif line.startswith("deleted file mode"):
            current.status = "deleted"
        elif line.startswith("rename to "):
            current.status = "renamed"
        elif line.startswith("GIT binary patch") or line.startswith("Binary files"):
            current.binary = True
        elif line.startswith("+") and not line.startswith("+++"):
            current.added += 1
        elif line.startswith("-") and not line.startswith("---"):
            current.removed += 1
    for item in files:
        item.flags = _flags_for(item)
    return files


def _flags_for(item: PatchFile) -> list[str]:
    flags: list[str] = []
    name = item.path.rsplit("/", 1)[-1]
    if name in _LOCKFILES:
        flags.append("lockfile")
    if item.path.startswith(_CI_PREFIXES):
        flags.append("ci")
    if item.status == "deleted":
        flags.append("deleted")
    if item.binary:
        flags.append("binary")
    if _SECRET_LIKE.search(item.path):
        flags.append("secret_like")
    if item.added + item.removed > _LARGE_LINES:
        flags.append("large")
    return flags


# --------------------------------------------------------------------------
# Checks and apply, on the operator's folder
# --------------------------------------------------------------------------


@dataclass
class ApplyCheck:
    can_apply: bool = True
    blockers: list[str] = field(default_factory=list)
    warnings: list[str] = field(default_factory=list)
    head: str = ""
    head_moved_by: int | None = None
    overlapping_dirty: list[str] = field(default_factory=list)
    dirty_files: list[str] = field(default_factory=list)


_IN_PROGRESS = {
    "MERGE_HEAD": "a merge",
    "REBASE_HEAD": "a rebase",
    "rebase-merge": "a rebase",
    "rebase-apply": "a rebase or `git am`",
    "CHERRY_PICK_HEAD": "a cherry-pick",
    "REVERT_HEAD": "a revert",
    "BISECT_LOG": "a bisect",
}


def _git_dir(repo: Path) -> Path:
    out = _git_ok(["rev-parse", "--absolute-git-dir"], repo).strip()
    return Path(out)


def dirty_paths(repo: Path) -> list[str]:
    """Uncommitted paths, tracked or not, as the operator's ``git status`` shows."""
    code, out, _ = git(
        ["status", "--porcelain=v1", "-z", "--untracked-files=all"], repo
    )
    if code != 0:
        return []
    paths: list[str] = []
    entries = out.split("\0")
    index = 0
    while index < len(entries):
        entry = entries[index]
        index += 1
        if len(entry) < 4:
            continue
        status, path = entry[:2], entry[3:]
        paths.append(path)
        if status[0] in "RC":
            # A rename carries its source as the next NUL-separated entry.
            if index < len(entries) and entries[index]:
                paths.append(entries[index])
            index += 1
    return paths


def _patch_paths(files: list[PatchFile], patch: str) -> set[str]:
    paths = {item.path for item in files}
    for line in patch.splitlines():
        header = _DIFF_HEADER.match(line)
        if header:
            paths.add(header.group(1))
    return paths


def _commits_since(repo: Path, base_commit: str) -> int | None:
    code, out, _ = git(["rev-list", "--count", f"{base_commit}..HEAD"], repo)
    if code != 0:
        return None
    try:
        return int(out.strip())
    except ValueError:
        return None


def _apply_args(reverse: bool) -> list[str]:
    args = ["apply", "--whitespace=nowarn", "--recount"]
    if reverse:
        args.append("--reverse")
    return args


def _with_patch_file(patch: str, repo: Path, args: list[str]) -> tuple[int, str]:
    # Outside the repository on purpose: a temp file inside it would show up in
    # the operator's `git status` if anything interrupted the cleanup.
    with tempfile.NamedTemporaryFile(
        "w", suffix=".patch", delete=False, encoding="utf-8"
    ) as handle:
        handle.write(patch if patch.endswith("\n") else patch + "\n")
        name = handle.name
    try:
        code, out, err = git([*args, name], repo, timeout=300)
    finally:
        os.unlink(name)
    return code, (err or out).strip()


def check_apply(
    repo: Path, patch: str, base_commit: str = "", *, reverse: bool = False
) -> ApplyCheck:
    """Everything that could go wrong, answered without writing anything."""
    check = ApplyCheck()
    if not (repo / ".git").exists():
        check.blockers.append(f"{repo} is not a git repository (or is not mounted).")
        check.can_apply = False
        return check
    if not patch.strip():
        check.blockers.append("The change is empty: there is nothing to apply.")
        check.can_apply = False
        return check
    git_dir = _git_dir(repo)
    for marker, label in _IN_PROGRESS.items():
        if (git_dir / marker).exists():
            check.blockers.append(
                f"Your repository is in the middle of {label}. Finish or abort it first."
            )
    if (git_dir / "index.lock").exists():
        check.blockers.append(
            "Another git process holds the index (.git/index.lock). Wait for it, "
            "or remove the lock if nothing is running."
        )
    code, head, _ = git(["rev-parse", "HEAD"], repo)
    check.head = head.strip() if code == 0 else ""
    if base_commit and not reverse:
        moved = _commits_since(repo, base_commit)
        check.head_moved_by = moved
        if moved is None:
            check.warnings.append(
                "The task's base commit is not in your current history (another "
                "branch, or a rebase). The change may not fit."
            )
        elif moved > 0:
            check.warnings.append(
                f"Your repository moved {moved} commit(s) since the task was created."
            )
    files = summarize_patch(patch)
    touched = _patch_paths(files, patch)
    check.dirty_files = dirty_paths(repo)
    check.overlapping_dirty = sorted(set(check.dirty_files) & touched)
    if check.overlapping_dirty and not reverse:
        shown = ", ".join(check.overlapping_dirty[:10])
        check.blockers.append(
            "You have uncommitted changes in files this change touches: "
            f"{shown}. Commit or stash them first."
        )
    elif check.dirty_files and not reverse:
        check.warnings.append(
            f"You have {len(check.dirty_files)} uncommitted change(s) in other "
            "files; they are left as they are."
        )
    if not check.blockers:
        code, detail = _with_patch_file(patch, repo, [*_apply_args(reverse), "--check"])
        if code != 0:
            check.blockers.append(
                (
                    "The files changed since this change was applied, so it cannot "
                    "be undone automatically. Resolve it with git: "
                )
                if reverse
                else "The change does not fit your current files: "
            )
            check.blockers[-1] += detail[-600:]
    check.can_apply = not check.blockers
    return check


def apply_patch(
    repo: Path, patch: str, base_commit: str = "", *, reverse: bool = False
) -> ApplyCheck:
    """Check, then apply (or reverse) the patch to the working tree only."""
    check = check_apply(repo, patch, base_commit, reverse=reverse)
    if not check.can_apply:
        return check
    code, detail = _with_patch_file(patch, repo, _apply_args(reverse))
    if code != 0:
        check.can_apply = False
        check.blockers.append(f"git apply failed: {detail[-600:]}")
    return check


# --------------------------------------------------------------------------
# CLI — what the apply container runs
# --------------------------------------------------------------------------


def main(argv: list[str] | None = None) -> int:
    """``adhoc_git.py <check|apply|undo> <repo> <patch-file> [base_commit]``.

    Prints one JSON object (the ``ApplyCheck``) on stdout. Exit 0 when the
    operation went through (or, for ``check``, when it would), 1 when refused.
    """
    args = list(sys.argv[1:] if argv is None else argv)
    if len(args) < 3 or args[0] not in {"check", "apply", "undo"}:
        sys.stderr.write(main.__doc__ or "")
        return 2
    action, repo, patch_file = args[0], Path(args[1]), Path(args[2])
    base_commit = args[3] if len(args) > 3 else ""
    patch = patch_file.read_text(encoding="utf-8")
    reverse = action == "undo"
    try:
        if action == "check":
            result = check_apply(repo, patch, base_commit)
        else:
            result = apply_patch(repo, patch, base_commit, reverse=reverse)
    except AdhocGitError as exc:
        result = ApplyCheck(can_apply=False, blockers=[str(exc)])
    sys.stdout.write(json.dumps(asdict(result)) + "\n")
    return 0 if result.can_apply else 1


if __name__ == "__main__":  # pragma: no cover - exercised inside the container
    raise SystemExit(main())
