"""Git operations behind ad hoc tasks: the clean patch, and applying it (ADR-0095).

Standard library only, on purpose. The same file runs in three places: inside
the runner container (to build the patch where the agent ran), inside the
lab's own processes (to read a patch and check it against a folder), and as
``python adhoc_git.py`` inside the short-lived container that mounts the
operator's folder read-write. None of those may depend on the lab's settings or
database, so nothing here imports from ``harness_lab_app``.

Three rules make "apply" safe on somebody's working copy:

* **all or nothing** — ``git apply`` refuses the whole patch when one hunk does
  not fit, so a failed apply leaves the folder exactly as it was;
* **files only** — no ``--index``, no commit, no branch, no stash: the change
  appears as uncommitted edits and the operator commits it themselves;
* **check first** — an operation in progress, a held index lock, or an
  uncommitted edit in a file the patch touches refuses before anything is
  written.

Two rules make the patch trustworthy:

* **bytes, never text** — a patch is not UTF-8: CRLF line endings, Latin-1
  sources and binary hunks must survive byte for byte or ``git apply`` rejects
  the result;
* **an agent's repository is hostile** — the agent could write ``core.fsmonitor``,
  a filter driver or an external diff into its copy's ``.git/config``, and git
  would run it. Every git call on such a directory goes through
  :func:`git_untrusted`, which neutralises each configured hook point; and the
  patch is built inside the runner container, where the agent already ran.
"""

