def main(argv: list[str] | None = None) -> int:
    """Two entry points, one JSON object on stdout.

    ``adhoc_git.py <check|apply|undo> <repo> <patch-file> [base] [hashes-json]``
    — exit 0 when the operation went through (or, for ``check``, would), 1 when
    refused.

    ``adhoc_git.py build <workspace> <base_commit> <out-patch> [diff-from]`` —
    writes the patch bytes; exit 0 on success.
    """
    args = list(sys.argv[1:] if argv is None else argv)
    if len(args) >= 4 and args[0] == "build":
        workspace, base_commit, out = Path(args[1]), args[2], Path(args[3])
        diff_from = args[4] if len(args) > 4 else ""
        try:
            patch = build_change_patch(workspace, base_commit, diff_from)
        except (AdhocGitError, OSError) as exc:
            sys.stdout.write(json.dumps({"ok": False, "error": str(exc)}) + "\n")
            return 1
        out.write_bytes(patch)
        sys.stdout.write(json.dumps({"ok": True, "bytes": len(patch)}) + "\n")
        return 0
    if len(args) < 3 or args[0] not in {"check", "apply", "undo"}:
        sys.stderr.write(main.__doc__ or "")
        return 2
    action, repo, patch_file = args[0], Path(args[1]), Path(args[2])
    base_commit = args[3] if len(args) > 3 else ""
    expected: dict[str, str] | None = None
    if len(args) > 4 and args[4]:
        expected = json.loads(args[4])
    patch = patch_file.read_bytes()
    reverse = action == "undo"
    try:
        if action == "check":
            result = check_apply(repo, patch, base_commit)
        else:
            result = apply_patch(
                repo, patch, base_commit, reverse=reverse, expected_hashes=expected
            )
            if not result.can_apply and not reverse and already_applied(repo, patch):
                # A redelivered apply: the folder already holds this change.
                result = ApplyCheck(
                    can_apply=True,
                    warnings=["The change was already applied to this folder."],
                    applied_hashes=file_hashes(
                        repo, [i.path for i in summarize_patch(patch, repo)]
                    ),
                )
    except AdhocGitError as exc:
        result = ApplyCheck(can_apply=False, blockers=[str(exc)])
    sys.stdout.write(json.dumps(asdict(result)) + "\n")
    return 0 if result.can_apply else 1


