@dataclass
class ApplyCheck:
    can_apply: bool = True
    blockers: list[str] = field(default_factory=list)
    warnings: list[str] = field(default_factory=list)
    head: str = ""
    head_moved_by: int | None = None
    overlapping_dirty: list[str] = field(default_factory=list)
    dirty_files: list[str] = field(default_factory=list)
    # Content hash of every touched path after an apply ("" = absent). Stored by
    # the lab and handed back on undo, which refuses if any path changed since.
    applied_hashes: dict[str, str] = field(default_factory=dict)


_IN_PROGRESS = {
    "MERGE_HEAD": "a merge",
    "REBASE_HEAD": "a rebase",
    "rebase-merge": "a rebase",
    "rebase-apply": "a rebase or `git am`",
    "CHERRY_PICK_HEAD": "a cherry-pick",
    "REVERT_HEAD": "a revert",
    "BISECT_LOG": "a bisect",
}


def _git_dir(repo: Path) -> Path:
    code, out, err = git(["rev-parse", "--absolute-git-dir"], repo)
    if code != 0:
        raise AdhocGitError(f"Not a git repository: {err.strip()}")
    return Path(out.strip())


def dirty_paths(repo: Path) -> list[str]:
    """Uncommitted paths, tracked or not, as the operator's ``git status`` shows."""
    code, out, _ = git_bytes(
        ["status", "--porcelain=v1", "-z", "--untracked-files=all"], repo
    )
    if code != 0:
        return []
    paths: list[str] = []
    entries = out.split(b"\0")
    index = 0
    while index < len(entries):
        entry = entries[index]
        index += 1
        if len(entry) < 4:
            continue
        status, path = entry[:2], entry[3:]
        paths.append(path.decode("utf-8", errors="replace"))
        if status[:1] in (b"R", b"C"):
            # A rename carries its source as the next NUL-separated entry.
            if index < len(entries) and entries[index]:
                paths.append(entries[index].decode("utf-8", errors="replace"))
            index += 1
    return paths


def _commits_since(repo: Path, base_commit: str) -> int | None:
    code, out, _ = git(["rev-list", "--count", f"{base_commit}..HEAD"], repo)
    if code != 0:
        return None
    try:
        return int(out.strip())
    except ValueError:
        return None


def _apply_args(reverse: bool) -> list[str]:
    args = ["apply", "--whitespace=nowarn", "--recount"]
    if reverse:
        args.append("--reverse")
    return args


def _with_patch_file(patch: bytes, repo: Path, args: list[str]) -> tuple[int, str]:
    # Outside the repository on purpose: a temp file inside it would show up in
    # the operator's `git status` if anything interrupted the cleanup.
    with tempfile.NamedTemporaryFile("wb", suffix=".patch", delete=False) as handle:
        handle.write(patch if patch.endswith(b"\n") else patch + b"\n")
        name = handle.name
    try:
        code, out, err = git_bytes([*args, name], repo, timeout=300)
    finally:
        os.unlink(name)
    return code, (err or out).decode("utf-8", errors="replace").strip()


def file_hashes(repo: Path, paths: list[str]) -> dict[str, str]:
    """SHA-256 of each path's bytes in the working tree; "" when absent."""
    hashes: dict[str, str] = {}
    root = repo.resolve()
    for path in paths:
        target = (root / path).resolve()
        if target != root and root not in target.parents:
            hashes[path] = "?"
            continue
        try:
            hashes[path] = hashlib.sha256(target.read_bytes()).hexdigest()
        except FileNotFoundError:
            hashes[path] = ""
        except OSError:
            hashes[path] = "?"
    return hashes


def check_apply(
    repo: Path,
    patch: bytes,
    base_commit: str = "",
    *,
    reverse: bool = False,
    expected_hashes: dict[str, str] | None = None,
) -> ApplyCheck:
    """Everything that could go wrong, answered without writing anything."""
    check = ApplyCheck()
    if not (repo / ".git").exists():
        check.blockers.append(f"{repo} is not a git repository (or is not mounted).")
        check.can_apply = False
        return check
    if not patch.strip():
        check.blockers.append("The change is empty: there is nothing to apply.")
        check.can_apply = False
        return check
    git_dir = _git_dir(repo)
    for marker, label in _IN_PROGRESS.items():
        if (git_dir / marker).exists():
            check.blockers.append(
                f"Your repository is in the middle of {label}. Finish or abort it first."
            )
    if (git_dir / "index.lock").exists():
        check.blockers.append(
            "Another git process holds the index (.git/index.lock). Wait for it, "
            "or remove the lock if nothing is running."
        )
    code, head, _ = git(["rev-parse", "HEAD"], repo)
    check.head = head.strip() if code == 0 else ""
    touched = [item.path for item in summarize_patch(patch, repo)]
    if not touched:
        check.blockers.append("The change lists no files git can read.")
    if base_commit and not reverse:
        moved = _commits_since(repo, base_commit)
        check.head_moved_by = moved
        if moved is None:
            check.warnings.append(
                "The task's base commit is not in your current history (another "
                "branch, or a rebase). The change may not fit."
            )
        elif moved > 0:
            check.warnings.append(
                f"Your repository moved {moved} commit(s) since the task was created."
            )
    check.dirty_files = dirty_paths(repo)
    if reverse:
        if expected_hashes:
            now = file_hashes(repo, list(expected_hashes))
            changed = sorted(p for p, h in expected_hashes.items() if now.get(p) != h)
            if changed:
                check.blockers.append(
                    "These files changed since the change was applied, so undoing "
                    "it could discard your edits: "
                    f"{', '.join(changed[:10])}. Resolve it with git."
                )
        else:
            check.warnings.append(
                "This change was applied before the lab recorded file hashes; "
                "undo relies on git alone."
            )
    else:
        check.overlapping_dirty = sorted(set(check.dirty_files) & set(touched))
        if check.overlapping_dirty:
            shown = ", ".join(check.overlapping_dirty[:10])
            check.blockers.append(
                "You have uncommitted changes in files this change touches: "
                f"{shown}. Commit or stash them first."
            )
        elif check.dirty_files:
            check.warnings.append(
                f"You have {len(check.dirty_files)} uncommitted change(s) in other "
                "files; they are left as they are."
            )
    if not check.blockers:
        code, detail = _with_patch_file(patch, repo, [*_apply_args(reverse), "--check"])
        if code != 0:
            prefix = (
                "The files no longer match the applied change, so it cannot be "
                "undone automatically. Resolve it with git: "
                if reverse
                else "The change does not fit your current files: "
            )
            check.blockers.append(prefix + detail[-600:])
    check.can_apply = not check.blockers
    return check


def apply_patch(
    repo: Path,
    patch: bytes,
    base_commit: str = "",
    *,
    reverse: bool = False,
    expected_hashes: dict[str, str] | None = None,
) -> ApplyCheck:
    """Check, then apply (or reverse) the patch to the working tree only."""
    check = check_apply(
        repo, patch, base_commit, reverse=reverse, expected_hashes=expected_hashes
    )
    if not check.can_apply:
        return check
    code, detail = _with_patch_file(patch, repo, _apply_args(reverse))
    if code != 0:
        check.can_apply = False
        check.blockers.append(f"git apply failed: {detail[-600:]}")
        return check
    if not reverse:
        check.applied_hashes = file_hashes(
            repo, [item.path for item in summarize_patch(patch, repo)]
        )
    return check


def already_applied(repo: Path, patch: bytes) -> bool:
    """Whether the folder already holds this change (its reverse fits)."""
    if not patch.strip():
        return False
    code, _ = _with_patch_file(patch, repo, [*_apply_args(True), "--check"])
    return code == 0


