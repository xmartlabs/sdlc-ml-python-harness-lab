@dataclass
class PatchFile:
    path: str
    added: int = 0
    removed: int = 0
    status: str = "modified"  # added | modified | deleted | renamed
    binary: bool = False
    flags: list[str] = field(default_factory=list)


def provisioned_commit(workspace: Path, base_commit: str) -> str:
    """The lab's provisioning commit on top of ``base_commit``, or "".

    A fallback for runs that did not record it: the runner now writes the SHA
    into ``provisioned_commit.txt`` the moment it creates the commit, and that
    recorded SHA wins (an agent can amend or reword the commit; it cannot
    change what was written before it started).
    """
    code, out, _ = git_untrusted(
        [
            "log",
            "--format=%H",
            "-n",
            "1",
            "--fixed-strings",
            f"--grep={PROVISIONED_SUBJECT}",
            f"{base_commit}..HEAD",
        ],
        workspace,
    )
    return out.decode().strip() if code == 0 else ""


HARNESS_PATHS_FILE = "harness_paths.json"


def read_harness_paths(run_dir: Path) -> list[str]:
    """The workspace paths the lab's harness occupies, as the runner recorded.

    Relative, normalised paths only: anything absolute or climbing out with
    ``..`` is dropped rather than trusted, since the list ends up in a pathspec.
    """
    try:
        raw = json.loads((run_dir / HARNESS_PATHS_FILE).read_text())
    except (OSError, ValueError):
        return []
    if not isinstance(raw, list):
        return []
    paths: list[str] = []
    for item in raw:
        text = str(item).strip()
        # Checked before normalising: stripping first turned "/etc/x" into a
        # relative "etc/x" that looked harmless.
        if not text or text.startswith("/") or ".." in text.split("/"):
            continue
        paths.append(text.rstrip("/"))
    return sorted(set(paths))


def _pathspec_excludes(harness_paths: list[str] = ()) -> list[str]:  # type: ignore[assignment]
    excludes: list[str] = []
    for name in NOISE_DIRS:
        excludes.append(f":(exclude,glob){name}")
        excludes.append(f":(exclude,glob){name}/**")
        excludes.append(f":(exclude,glob)**/{name}")
        excludes.append(f":(exclude,glob)**/{name}/**")
    # The lab's harness, projected into the clone for this run: the operator
    # asked for their code, not for the lab's skills (ADR-0095). `literal`
    # anchors at the workspace root and reads no glob characters in a name.
    for path in harness_paths:
        excludes.append(f":(exclude,literal){path}")
    return excludes


def build_change_patch(
    workspace: Path,
    base_commit: str,
    diff_from: str = "",
    harness_paths: list[str] = (),  # type: ignore[assignment]
) -> bytes:
    """The agent's change, as bytes ready for ``git apply`` on the operator's commit.

    Diffed against the lab's provisioning commit (``diff_from``, recorded by the
    runner), not against ``base_commit``: the provisioning commit already holds
    setup output and any projected harness, so neither leaks into the
    operator's repository as if the agent had written it. A diff against a
    commit (not ``HEAD``) also survives an agent that committed its own work.

    ``--binary`` so a binary file is carried, ``--no-textconv``/``--no-ext-diff``
    so nothing the agent configured rewrites the content, and the output kept as
    bytes so CRLF and non-UTF-8 files survive. Intent-to-add makes new files
    visible without staging their content; ``.gitignore`` still applies.

    ``harness_paths`` are the lab harness's files in the clone (skills, agents,
    adapter files). They sit in the provisioning commit already; excluding
    them also drops an agent's edits to them, which belong to the lab's
    harness and never to the operator's repository.
    """
    if not (workspace / ".git").exists():
        raise AdhocGitError(f"{workspace} is not a git repository.")
    base = diff_from or provisioned_commit(workspace, base_commit) or base_commit
    _git_ok_untrusted(["add", "--intent-to-add", "--all", "--", "."], workspace)
    return _git_ok_untrusted(
        [
            "diff",
            "--binary",
            "--full-index",
            "--no-color",
            "--no-ext-diff",
            "--no-textconv",
            base,
            "--",
            ".",
            *_pathspec_excludes(harness_paths),
        ],
        workspace,
    )


def _numstat(patch: bytes) -> list[tuple[str, int, int, bool]]:
    """Per-file counts straight from git, NUL-separated so any path survives.

    Always run in a fresh empty directory outside any repository. Run inside a
    repository's subdirectory (the lab's own ``data/runs/<id>/`` is one), ``git
    apply`` reads every path as relative to that subdirectory and silently
    drops the ones outside it — which is all of them, so the count was empty.
    """
    with tempfile.TemporaryDirectory() as scratch:
        code, out, _ = _run(
            ["apply", "--numstat", "-z", "--recount", "-"],
            Path(scratch),
            {**_config_env(), "GIT_CEILING_DIRECTORIES": scratch},
            120,
            patch,
        )
    if code != 0:
        return []
    rows: list[tuple[str, int, int, bool]] = []
    for record in out.split(b"\0"):
        if not record:
            continue
        parts = record.split(b"\t", 2)
        if len(parts) != 3:
            continue
        added, removed, path = parts
        binary = added == b"-"
        rows.append(
            (
                path.decode("utf-8", errors="replace"),
                0 if binary else int(added),
                0 if binary else int(removed),
                binary,
            )
        )
    return rows


_HEADER_NEW = re.compile(rb"^\+\+\+ (?:b/(.*)|/dev/null)$")
_HEADER_OLD = re.compile(rb"^--- (?:a/(.*)|/dev/null)$")


def _statuses(patch: bytes) -> dict[str, str]:
    """added/deleted per path, read from the ``---``/``+++`` headers.

    Those headers carry the path unquoted when ``core.quotePath=false`` (which
    every patch built here uses), unlike ``diff --git``, whose two paths cannot
    be split reliably when one contains `` b/``.
    """
    statuses: dict[str, str] = {}
    old: bytes | None = None
    new_file = deleted = False
    for line in patch.split(b"\n"):
        if line.startswith(b"diff --git "):
            old, new_file, deleted = None, False, False
        elif line.startswith(b"new file mode"):
            new_file = True
        elif line.startswith(b"deleted file mode"):
            deleted = True
        elif (match := _HEADER_OLD.match(line)) is not None:
            old = match.group(1)
        elif (match := _HEADER_NEW.match(line)) is not None:
            path = match.group(1) or old
            if path is not None:
                status = "added" if new_file else "deleted" if deleted else "modified"
                statuses[path.decode("utf-8", errors="replace")] = status
        elif line.startswith(b"Binary files ") or line.startswith(b"GIT binary patch"):
            continue
    return statuses


def summarize_patch(patch: bytes | str, cwd: Path | None = None) -> list[PatchFile]:
    """Per-file counts and review flags.

    Counts come from ``git apply --numstat -z`` (any path, binary detected by
    git itself); statuses come from the patch headers. ``cwd`` is accepted for
    callers' convenience and ignored: the count must not run inside a repository.
    """
    del cwd
    data = patch.encode("utf-8") if isinstance(patch, str) else patch
    if not data.strip():
        return []
    statuses = _statuses(data)
    files: list[PatchFile] = []
    for path, added, removed, binary in _numstat(data):
        item = PatchFile(
            path=path,
            added=added,
            removed=removed,
            binary=binary,
            status=statuses.get(path, "modified"),
        )
        item.flags = _flags_for(item)
        files.append(item)
    return files


def _flags_for(item: PatchFile) -> list[str]:
    flags: list[str] = []
    name = item.path.rsplit("/", 1)[-1]
    if name in _LOCKFILES:
        flags.append("lockfile")
    if item.path.startswith(_CI_PREFIXES):
        flags.append("ci")
    if item.status == "deleted":
        flags.append("deleted")
    if item.binary:
        flags.append("binary")
    if _SECRET_LIKE.search(item.path):
        flags.append("secret_like")
    if item.added + item.removed > _LARGE_LINES:
        flags.append("large")
    return flags


